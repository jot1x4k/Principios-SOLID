package co.lsp;

public class Rectangulo {
    public double alto;
    public double ancho;

    public double CalcularArea() {
        return alto * ancho;
    }

    public double getAlto() {
        return alto;
    }
    public void setAlto(double alto) {
        this.alto = alto;
    }
    public double getAncho() {
        return ancho;
    }
    public void setAncho(double ancho) {
        this.ancho = ancho;
    }

    
}
